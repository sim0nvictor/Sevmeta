function getInitialLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (savedLanguage in translations) return savedLanguage;
  } catch (error) {
    console.warn("Unable to read the saved language preference.", error);
  }

  const browserLanguages = navigator.languages?.length
    ? navigator.languages
    : [navigator.language];
  const preferredLanguage = browserLanguages.find((language) =>
    Object.keys(translations).some((supported) => language?.toLowerCase().startsWith(supported))
  );
  return preferredLanguage?.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function I18nProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (nextLanguage) => {
    if (!(nextLanguage in translations)) return;
    setLanguageState(nextLanguage);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    } catch (error) {
      console.warn("Unable to save the language preference.", error);
    }
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t(key) {
      const resolve = (catalog) => key.split(".").reduce((result, part) => result?.[part], catalog);
      return resolve(translations[language]) ?? resolve(translations.en) ?? key;
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
